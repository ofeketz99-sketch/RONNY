'use strict';
const {test}=require('node:test');
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const vm=require('node:vm');
const source=fs.readFileSync(path.join(__dirname,'../scripts/src/00g-trip-state-commands.js'),'utf8');
const commands=vm.runInNewContext(source+'\nTripStateCommands');
const clone=o=>JSON.parse(JSON.stringify(o));
const isMapOnlyPoint=p=>new Set(['poi','note','idea']).has(p?.type);
test('reorder route stops while preserving map-only points and object identities',()=>{
 const start={id:'start',type:'start'},via={id:'via',type:'via'},poi={id:'poi',type:'poi'};
 const trip={days:[{stops:[start,poi,via]}]};
 commands.commitRouteOrder(trip,0,[via,start],isMapOnlyPoint);
 assert.equal(trip.days[0].stops[0],via);
 assert.equal(trip.days[0].stops[1],start);
 assert.equal(trip.days[0].stops[2],poi);
 commands.commitRouteOrder(trip,99,[start],isMapOnlyPoint);
 assert.equal(trip.days.length,1);
});
test('renumber only generic day names, retain custom names',()=>{
 const trip={days:[{label:'יום 9'},{label:'טיול בהרים'},{label:'יום 1'}]};
 commands.renumberGenericDayLabels(trip);
 assert.deepEqual(JSON.parse(JSON.stringify(trip.days.map(d=>d.label))),['יום 1','טיול בהרים','יום 3']);
});
test('unique endpoint enforcement reclassifies duplicates without deleting content',()=>{
 const start={id:'s',type:'start',name:'נקודת התחלה'};
 const other={id:'other',type:'start',name:'נקודת התחלה',autoChronoName:true};
 const day={stops:[start,other]};
 assert.equal(commands.enforceRouteEndpoints(day,start),true);
 assert.equal(other.type,'via');
 assert.equal(other.name,'נקודת מעבר');
 assert.equal(other.autoViaName,true);
 assert.equal(commands.enforceRouteEndpoints(day,start),false);
});
test('endpoint ordering keeps distinct map-only stops at end and invokes renumber once',()=>{
 const start={id:'start',type:'start'},end={id:'end',type:'end'},middle={id:'middle',type:'via'},note={id:'note',type:'note'};
 const day={stops:[note,end,middle,start]};let calls=0;
 commands.positionRouteEndpoints(day,isMapOnlyPoint,()=>{calls++});
 assert.deepEqual(JSON.parse(JSON.stringify(day.stops.map(s=>s.id))),['start','middle','end','note']);
 assert.equal(day.stops[1],middle);
 assert.equal(calls,1);
});
test('chronological endpoints update autogenerated names without replacing user names',()=>{
 const trip={days:[{loop:false,stops:[{id:'s',type:'start',name:'נקודת התחלה'},{id:'p',type:'via',name:'נקודת סיום',autoChronoName:true},{id:'e',type:'end',name:'My hotel'}]},{loop:true,stops:[{id:'s2',type:'start',name:'נקודת התחלה'},{id:'e2',type:'end',name:'נקודת סיום'}]}]};
 assert.equal(commands.synchronizeChronologicalEndpointNames(trip),true);
 assert.equal(trip.days[0].stops[0].name,'נקודת יציאה יום 1');
 assert.equal(trip.days[0].stops[1].name,'נקודת מעבר');
 assert.equal(trip.days[0].stops[2].name,'My hotel');
 assert.equal(trip.days[1].stops[0].name,'נקודת התחלה/סיום יום 2');
 assert.equal(trip.days[1].stops[1].name,'נקודת סיום יום 2');
 assert.equal(commands.synchronizeChronologicalEndpointNames(trip),false);
});
test('pre-render normalization respects original sequencing and view-dependent start sync',()=>{
 for(const isDay of [false,true]){
  const called=[];
  const deps={syncWalkingLoops:()=>{called.push('walking');return false},
   synchronizeLoopDays:()=>{called.push('loop');return false},
   synchronizeDayStarts:()=>{called.push('starts');return true},
   synchronizeChronologicalEndpointNames:()=>{called.push('names');return false}};
  const changed=commands.synchronizeForRender({days:[{},{}]},isDay,deps);
  assert.equal(changed,isDay);
  assert.deepEqual(JSON.parse(JSON.stringify(called)),isDay?['walking','walking','starts','loop','names']:['walking','walking','loop','names']);
 }
});

test('linked start coordinates are resolved before generated circular endpoints',()=>{
 const trip={days:[{stops:[{type:'start',lat:1,lng:2}]},{loop:true,stops:[{type:'start',lat:1,lng:2},{type:'end',autoLoopEnd:true,lat:1,lng:2}]}]};
 const observed=[];
 const deps={syncWalkingLoops:()=>false,synchronizeDayStarts:()=>{trip.days[1].stops[0].lat=7;observed.push('inherit');return true},synchronizeLoopDays:()=>{trip.days[1].stops[1].lat=trip.days[1].stops[0].lat;observed.push('loop');return true},synchronizeChronologicalEndpointNames:()=>false};
 assert.equal(commands.synchronizeForRender(trip,true,deps),true);
 assert.deepEqual(observed,['inherit','loop']);
 assert.equal(trip.days[1].stops[1].lat,7);
});
