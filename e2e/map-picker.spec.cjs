'use strict';
const {test,expect}=require('@playwright/test');
test('on-map picker changes supplemental maps immediately and keeps saved style on reload',async({page})=>{
 await page.goto('/index.html',{waitUntil:'domcontentloaded'});
 await expect(page.locator('#map.leaflet-container')).toBeVisible();
 const trigger=page.locator('#map-picker-toggle'),menu=page.locator('#map-picker-menu'),switcher=page.locator('#map-base-switch');
 await expect(trigger).toBeVisible();
 await expect(menu).toBeHidden();
 await trigger.click();
 await expect(menu).toBeVisible();
 await expect(trigger).toHaveAttribute('aria-expanded','true');
 await expect(menu.locator('[data-map-choice]')).toHaveCount(7);
 await expect(menu.locator('[data-map-choice="satellite"]')).toHaveCount(0);
 await expect(menu.locator('[data-map-choice="topo"]')).toHaveCount(0);
 await menu.locator('[data-map-choice="osm"]').click();
 await expect(menu).toBeHidden();
 await expect(trigger).toHaveAttribute('aria-pressed','true');
 await expect(page.locator('#map-style')).toHaveValue('osm');
 await expect(switcher).toHaveAttribute('data-style','other');
 await expect(switcher.locator('[aria-checked="true"]')).toHaveCount(0);
 await trigger.click();
 await expect(menu.locator('[data-map-choice="osm"]')).toHaveAttribute('aria-checked','true');
 await page.keyboard.press('Escape');
 await expect(menu).toBeHidden();
 await expect(trigger).toHaveAttribute('aria-expanded','false');
 await trigger.click();
 await expect(menu).toBeVisible();
 await page.locator('#place-search').click();
 await expect(menu).toBeHidden();
 await page.reload({waitUntil:'domcontentloaded'});
 await expect(page.locator('#map.leaflet-container')).toBeVisible();
 await expect(page.locator('#map-style')).toHaveValue('osm');
 await expect(trigger).toHaveAttribute('aria-pressed','true');
 await switcher.locator('[data-map-base="satellite"]').click();
 await expect(switcher).toHaveAttribute('data-style','satellite');
 await expect(trigger).toHaveAttribute('aria-pressed','false');
 await expect(page.locator('#map-style')).toHaveValue('satellite');
});
